import { Channel, invoke } from "@tauri-apps/api/core";

export interface ModelInfo {
  name: string;
  size: number;
  params: string;
  quant: string;
  family: string;
}

export interface ChatMsg { role: "system" | "user" | "assistant"; content: string }

export interface ChatOptions {
  baseUrl: string;
  model: string;
  system: string;
  messages: ChatMsg[];
  temperature: number;
  numCtx: number;
}

interface ChatEvent {
  delta?: string | null;
  done: boolean;
  error?: string | null;
  evalCount?: number | null;
  totalMs?: number | null;
}

export const isDesktop = () => typeof window !== "undefined" && "__TAURI_INTERNALS__" in window;

const MOCK_MODELS: ModelInfo[] = [
  { name: "llama3.2:3b", size: 2_019_393_188, params: "3.2B", quant: "Q4_K_M", family: "llama" },
  { name: "qwen2.5:7b", size: 4_683_090_664, params: "7.6B", quant: "Q4_K_M", family: "qwen2" },
  { name: "mistral:7b", size: 4_368_437_122, params: "7.2B", quant: "Q4_0", family: "llama" },
];

export async function listModels(baseUrl: string): Promise<ModelInfo[]> {
  if (!isDesktop()) {
    await new Promise((r) => setTimeout(r, 120));
    return MOCK_MODELS;
  }
  return invoke<ModelInfo[]>("list_models", { baseUrl });
}

export async function ping(baseUrl: string): Promise<boolean> {
  if (!isDesktop()) return true;
  try { return await invoke<boolean>("ping", { baseUrl }); } catch { return false; }
}

let activeId: string | null = null;

export function streamChat(
  opts: ChatOptions,
  handlers: { onDelta: (t: string) => void; onDone: (e: { stopped: boolean }) => void; onError: (m: string) => void },
): string {
  const requestId = Math.random().toString(36).slice(2);
  activeId = requestId;

  if (!isDesktop()) {
    const canned = mockReply(opts);
    let i = 0;
    let stopped = false;
    const timer = setInterval(() => {
      if (activeId !== requestId) stopped = true;
      if (stopped) { clearInterval(timer); handlers.onDone({ stopped: true }); return; }
      const step = 3 + Math.floor(Math.random() * 5);
      handlers.onDelta(canned.slice(i, i + step));
      i += step;
      if (i >= canned.length) { clearInterval(timer); handlers.onDone({ stopped: false }); }
    }, 16);
    return requestId;
  }

  const channel = new Channel<ChatEvent>();
  channel.onmessage = (event) => {
    if (event.error) { handlers.onError(event.error); return; }
    if (event.delta) handlers.onDelta(event.delta);
    if (event.done) {
      if (activeId === requestId) activeId = null;
      handlers.onDone({ stopped: false });
    }
  };

  invoke("chat", {
    args: {
      baseUrl: opts.baseUrl,
      model: opts.model,
      system: opts.system,
      messages: opts.messages,
      temperature: opts.temperature,
      numCtx: opts.numCtx,
      requestId,
    },
    onEvent: channel,
  }).catch((err) => {
    if (activeId === requestId) activeId = null;
    handlers.onError(String(err));
  });

  return requestId;
}

export async function stopChat(): Promise<void> {
  const id = activeId;
  activeId = null;
  if (!id) return;
  if (isDesktop()) {
    try { await invoke("cancel_chat", { requestId: id }); } catch { /* ignore */ }
  }
}

function mockReply(opts: ChatOptions): string {
  const last = opts.messages.filter((m) => m.role === "user").at(-1)?.content ?? "your question";
  const short = last.length > 70 ? last.slice(0, 70).trim() + "…" : last;
  return `Here's the short version on **${short}**

Running locally means the model never leaves your machine. Everything below is generated by \`${opts.model || "your local model"}\`:

1. **Check the basics first** — restart the model if the first token stalls.
2. Keep the context window tight; 4k tokens is plenty for most chats.
3. If an answer looks thin, raise the temperature slightly and ask again.

\`\`\`bash
curl http://127.0.0.1:11434/api/tags
\`\`\`

Want me to go deeper on any of those?`;
}
